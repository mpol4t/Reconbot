// Exercise the installed application's graph with isolated, recorded artifacts.
const { _electron, expect } = require('../node_modules/@playwright/test');
const fs = require('fs'), path = require('path'), os = require('os'), assert = require('assert/strict');
(async () => {
  const root=path.resolve(__dirname,'..'), data=fs.mkdtempSync(path.join(os.tmpdir(),'reconbot-native-graph-'));
  const env={...process.env,RECONBOT_E2E_USER_DATA_DIR:data};
  for(const key of ['RECONBOT_REPO_ROOT','RECONBOT_PYTHON','RECONBOT_E2E','PYTHONPATH','VIRTUAL_ENV'])delete env[key];
  const executablePath=process.env.RECONBOT_SMOKE_EXECUTABLE||path.join(root,'dist/mac-arm64/ReconBot.app/Contents/MacOS/ReconBot');
  const app=await _electron.launch({executablePath,args:process.platform==='linux'&&process.getuid()===0?['--no-sandbox']:[],cwd:os.tmpdir(),env});
  try {
    const p=await app.firstWindow(),errors=[];p.on('pageerror',e=>errors.push(e.message));await p.locator('.nav-rail').waitFor();
    const info=await app.evaluate(async({app,ipcMain})=>({name:app.getName(),packaged:app.isPackaged,defaults:await ipcMain._invokeHandlers.get('config:get-defaults')({})}));
    assert.equal(info.name,'ReconBot');assert.equal(info.packaged,true);
    const run=path.join(info.defaults.outputDir,'runs','graph-smoke');fs.mkdirSync(run,{recursive:true});
    const output=path.join(run,'nuclei_output.jsonl');
    fs.writeFileSync(output,Array.from({length:35},(_,i)=>JSON.stringify({'template-id':'native-graph-'+i,info:{name:'Native graph finding '+i,severity:'high'},'matched-at':'https://graph.example/finding/'+i})).join('\n'));
    fs.writeFileSync(path.join(run,'run_result.json'),JSON.stringify({run_state:'completed',meta:{target:'https://graph.example'},summary:{katana_count:75,nuclei_findings_count:35},katana:{urls:Array.from({length:75},(_,i)=>'https://graph.example/discovery/'+i)},nuclei:{output_path:output},stages:{},auto_refresh_enabled:false}));
    await app.evaluate(async({ipcMain},dir)=>ipcMain._invokeHandlers.get('history:select-run')({},dir),run);
    await p.locator('.nav-rail [data-view="pipeline"]').click();
    const graph=p.locator('.evidence-graph');
    await expect(p.getByRole('button',{name:'Finding focus',exact:true})).toHaveAttribute('aria-pressed','true');
    await expect(graph.locator('[data-node-id^="finding:"]')).toHaveCount(12);
    const compactNodes=await graph.locator('[data-node-id]').count();
    await p.getByRole('button',{name:'Pause graph motion',exact:true}).click();
    const target=graph.locator('[data-node-id="target"]');
    await target.locator('.node-body').click();
    await expect(target).toHaveAttribute('aria-pressed','true');
    await target.locator('.node-body').click();
    await expect(graph.locator('[aria-pressed="true"]')).toHaveCount(0);
    await expect(graph.locator('.force-node.faded')).toHaveCount(0);
    await target.locator('.node-body').click();
    const canvas=await graph.boundingBox();await p.mouse.click(canvas.x+20,canvas.y+20);
    await expect(graph.locator('[aria-pressed="true"]')).toHaveCount(0);
    await target.focus();await p.keyboard.press('Enter');await p.keyboard.press('Escape');
    await expect(graph.locator('.force-node.faded')).toHaveCount(0);
    const scale=async()=>Number((await graph.locator('.graph-camera').getAttribute('transform')).match(/scale\(([^)]+)\)/)[1]);
    const box=await graph.boundingBox();await p.mouse.move(box.x+box.width*.45,box.y+box.height*.5);
    const beforeZoom=await scale();for(let i=0;i<20;i++)await p.mouse.wheel(0,1);
    await expect.poll(scale).toBeLessThan(beforeZoom*.99);assert(await scale()>beforeZoom*.97);
    await p.mouse.wheel(0,-20);await expect.poll(async()=>Math.abs(await scale()-beforeZoom)).toBeLessThan(1e-7);
    const discovery=graph.locator('[data-node-id="cluster:katana"]');
    await expect(discovery).toHaveAttribute('aria-expanded','false');
    await discovery.locator('.node-body').click();
    await expect(discovery).toHaveAttribute('aria-expanded','true');
    await expect(graph.locator('[data-node-id^="endpoint:"]')).toHaveCount(87);
    await expect(p.locator('.discovery-url-row')).toHaveCount(75);
    const address='https://graph.example/discovery/0';
    const row=p.locator('.discovery-url-row').first();
    await expect(row.locator('code')).toHaveText(address);
    await row.getByRole('button',{name:'Copy URL',exact:true}).click();
    await expect(row).toContainText('Copied');
    assert.equal(await app.evaluate(({clipboard})=>clipboard.readText()),address);
    await row.getByRole('button',{name:'Show on graph',exact:true}).click();
    await expect(p.locator('.graph-address-detail code')).toHaveText(address);
    await expect(graph.locator(`[data-node-id="endpoint:${address}"]`)).toHaveAttribute('aria-pressed','true');
    await discovery.locator('.force-label').click();
    await expect(discovery).toHaveAttribute('aria-expanded','false');
    await discovery.focus();await p.keyboard.press('Enter');
    await expect(discovery).toHaveAttribute('aria-expanded','true');
    await p.getByRole('button',{name:'Collapse URLs',exact:true}).click();
    await expect(graph.locator('[data-node-id^="endpoint:"]')).toHaveCount(12);
    await p.getByRole('button',{name:'Reset graph position',exact:true}).click();
    await expect(graph.locator('[aria-pressed="true"]')).toHaveCount(0);
    await expect(graph.locator('.force-node.faded')).toHaveCount(0);
    await p.locator('.pipeline-evidence-list .finding-card').filter({hasText:'Native graph finding 34'}).click();
    await expect(graph.locator('[data-node-id^="finding:"][aria-pressed="true"]')).toContainText('Native graph finding 34');
    await expect(p.locator('.pipeline-evidence-list .finding-card')).toHaveCount(1);
    await expect(graph.locator('[data-node-id^="finding:"]')).toHaveCount(13);
    await p.getByRole('button',{name:'All discovery data',exact:true}).click();
    await expect(graph.locator('[data-node-id^="finding:"]')).toHaveCount(36);
    await expect(graph.locator('[data-node-id^="endpoint:"]')).toHaveCount(110);
    await expect(graph.locator('[data-node-id^="cluster:"]')).toHaveCount(0);
    const fullNodes=await graph.locator('[data-node-id]').count();assert(compactNodes<fullNodes/3);assert.deepEqual(errors,[]);
    const result={name:info.name,packaged:true,platform:process.platform,compactNodes,fullNodes,graphInteractions:'passed',mouseActivation:'passed',selectionClear:'passed',addressInspector:'passed',clipboard:'passed',gentleWheelZoom:'passed',errors};
    fs.writeFileSync(process.env.RECONBOT_GRAPH_SMOKE_RESULT||path.join(root,'test-results/native-graph-smoke.json'),JSON.stringify(result,null,2));console.log(JSON.stringify(result));
  }finally{await app.close();fs.rmSync(data,{recursive:true,force:true});}
})().catch(error=>{console.error(error);process.exitCode=1});
